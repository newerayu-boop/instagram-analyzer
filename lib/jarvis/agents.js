// Профиль бизнеса — то, что превращает «умный чат» в «моего ассистента».
function profileBlock(user, facts) {
  const lines = Object.entries(facts || {}).map(([k, v]) => `- ${k}: ${v}`);
  return [
    'ЧТО ТЫ ЗНАЕШЬ ПРО ЭТОГО КЛИЕНТА',
    `Имя: ${user.name || 'не знаю'}`,
    lines.length ? lines.join('\n') : '- пока ничего; выясни нишу и запомни через remember',
    '',
    `Сегодня: ${new Date().toLocaleDateString('ru-RU', { timeZone: 'Asia/Tashkent' })}`,
  ].join('\n');
}

function systemFor(dept, user, facts) {
  const d = DEPARTMENTS[dept] || DEPARTMENTS.general;
  return [
    // Блок 1 — неизменный. Его кэшируем: одинаков для всех запросов
    // этого отдела, значит платим за него один раз в пять минут.
    { type: 'text', text: `${CORE}\n\n${d.prompt}`, cache_control: { type: 'ephemeral' } },
    // Блок 2 — меняется у каждого клиента и после каждого нового факта.
    // Он идёт ПОСЛЕ точки кэширования, иначе кэш ломался бы каждый раз.
    { type: 'text', text: profileBlock(user, facts) },
  ];
}

module.exports = { CORE, DEPARTMENTS, systemFor, profileBlock };
